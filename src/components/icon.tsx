export type IconName = keyof typeof ICON_PATHS;

interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name"> {
  name: IconName;
  /** Rendered box in px; the glyph scales inside the 256 Phosphor grid. */
  size?: number;
  /**
   * Accessible name. Omit it for decoration next to visible text; supply it
   * whenever the icon is the only content of a control.
   */
  title?: string;
}

export function Icon({ name, size = 18, title, ...props }: IconProps) {
  const shared: SVGProps<SVGSVGElement> = {
    className: "icon",
    fill: "currentColor",
    focusable: "false",
    height: size,
    viewBox: "0 0 256 256",
    width: size,
    ...props,
  };

  /* Decoration sits beside visible text, so assistive tech must skip it. */
  if (title === undefined) {
    return (
      <svg aria-hidden="true" {...shared}>
        <path d={ICON_PATHS[name]} />
      </svg>
    );
  }

  /* A named icon is the whole control, so it becomes an image with a name. */
  return (
    <svg role="img" {...shared}>
      <title>{title}</title>
      <path d={ICON_PATHS[name]} />
    </svg>
  );
}
